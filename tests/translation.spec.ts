import { test, expect } from '@playwright/test';

test('switching languages preserves inputs, comparison values and saved plans', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const tagalog = page.getByRole('button', { name: 'Tagalog', exact: true });
  await tagalog.focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('html')).toHaveAttribute('lang', 'tl');
  await expect(tagalog).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('heading', { name: 'Palaguin natin ang susunod na ani.' })).toBeVisible();
  await page.locator('.scene-cta').click();
  await page.getByLabel('Lawak ng bukid', { exact: false }).fill('2.5');
  await page.getByLabel('Panimulang badyet', { exact: false }).fill('90000');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await expect(page.getByLabel('Field area', { exact: false })).toHaveValue('2.5');
  await expect(page.getByLabel('Starting cash budget', { exact: false })).toHaveValue('90000');
  await tagalog.click();
  await page.getByRole('combobox', { name: 'Pag-agos ng tubig sa bukid', exact: true }).selectOption('well_drained');
  await page.getByRole('combobox', { name: /Mamimili para sa dalawang/ }).selectOption('available');
  await page.getByRole('button', { name: 'Ihambing ang mga maaaring itanim' }).click();
  await expect(page.getByRole('heading', { name: 'Mas malinaw na paghahambing.' })).toBeVisible();
  await expect(page.locator('.result-card.mungbean .status')).toHaveText('Angkop sa halimbawang ito');
  const metrics = await page.locator('.result-card.mungbean .result-metrics strong').allTextContents();
  await page.locator('.result-card.mungbean').getByRole('button', { name: 'Tingnan ang mga dahilan at palagay' }).click();
  await expect(page.getByRole('dialog')).toContainText('Kathang-isip');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'I-save ang paghahambing', exact: true }).click();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  const englishMetrics = await page.locator('.result-card.mungbean .result-metrics strong').allTextContents();
  expect(englishMetrics[0]).toBe(metrics[0]);
  expect(englishMetrics[3]).toBe(metrics[3]);
  await tagalog.click();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'tl');
  await expect(page.getByRole('button', { name: 'Tagalog', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: /Mga na-save na paghahambing/ }).click();
  await expect(page.locator('.history-card')).toHaveCount(1);
  await page.locator('.history-card').getByRole('button', { name: 'Buksan', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Mas malinaw na paghahambing.' })).toBeVisible();
  await page.getByRole('button', { name: 'Baguhin ang detalye', exact: true }).click();
  await expect(page.getByLabel('Lawak ng bukid', { exact: false })).toHaveValue('2.5');
  expect(errors).toEqual([]);
});

test('Tagalog control stays visible and translated mobile views remain usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  const tagalog = page.getByRole('button', { name: 'Tagalog', exact: true });
  await tagalog.click();
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await expect(tagalog).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/tagalog-overview-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Buksan ang menu', exact: true }).click();
  await page.getByRole('button', { name: 'Datos at hamon', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ang ebidensya sa likod ng ideya.' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Opisyal na hamon', exact: false })).toHaveAttribute('href', /spaceappschallenge.org/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Buksan ang menu', exact: true }).click();
  await page.getByRole('button', { name: 'Planuhin ang susunod na tanim', exact: true }).click();
  await page.getByLabel('Balak na petsa ng pagtatanim', { exact: true }).fill('2027-06-01');
  await page.getByRole('button', { name: 'Ihambing ang mga maaaring itanim' }).click();
  await expect(page.locator('.form-error[role=alert]')).toHaveText('Dapat mas huli ang petsa ng pagbabalik sa palay kaysa sa balak na petsa ng pagtatanim.');
  await page.getByRole('button', { name: 'Ibalik ang halimbawa', exact: true }).click();
  await page.getByRole('button', { name: 'Ihambing ang mga maaaring itanim' }).click();
  await expect(page.getByRole('heading', { name: 'Mas malinaw na paghahambing.' })).toBeVisible();
  await expect(page.locator('.result-card.mungbean .status')).toHaveText('Kailangang kumpirmahin');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/tagalog-comparison-mobile.png', fullPage: true });
});
